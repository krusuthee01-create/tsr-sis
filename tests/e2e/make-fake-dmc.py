def citizen_id():
    d = [random.randint(1, 9)] + [random.randint(0, 9) for _ in range(11)]
    s = sum(d[i] * (13 - i) for i in range(12))
    d.append((11 - s % 11) % 10)
    return "".join(map(str, d))


